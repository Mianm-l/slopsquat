"""
Scoring engine for assessing AI Hallucination and Slopsquatting risk.
"""

import re
from typing import Dict, Any, List

HALLUCINATION_SUFFIX_PATTERN = re.compile(
    r"[-_](helper|utils|util|tools|tool|wrapper|connector|manager|client|sdk|easy|simple|lite|parser|format|plus|pro|handler|lib)$",
    re.IGNORECASE
)

def evaluate_package_risk(inspected: Dict[str, Any]) -> Dict[str, Any]:
    """
    Evaluates risk score (0-100) and produces detailed diagnosis flags.
    """
    name = inspected["name"]
    exists = inspected.get("exists", False)
    error = inspected.get("error")
    age_days = inspected.get("age_days")
    downloads = inspected.get("monthly_downloads")
    total_releases = inspected.get("total_releases", 0)
    has_repo = inspected.get("has_repo", False)
    summary = inspected.get("summary", "")

    score = 0
    reasons: List[str] = []

    # Case 1: Package does NOT exist on the registry
    if not exists:
        if error == "NOT_FOUND":
            return {
                "name": name,
                "ecosystem": inspected.get("ecosystem", "unknown"),
                "score": 95,
                "level": "CRITICAL",
                "status": "UNREGISTERED_HALLUCINATION",
                "reasons": [
                    "Package does NOT exist on official registry.",
                    "High probability of hallucinated dependency generated by an AI assistant.",
                    "VULNERABILITY: Attackers can register this exact name on PyPI/npm at any time to hijack your build!"
                ],
                "action": "Remove immediately from dependency file, or inspect who introduced it."
            }
        else:
            return {
                "name": name,
                "ecosystem": inspected.get("ecosystem", "unknown"),
                "score": 0,
                "level": "UNKNOWN",
                "status": f"REGISTRY_ERROR: {error}",
                "reasons": [f"Failed to query registry: {error}"],
                "action": "Check network connection or try again."
            }

    # Case 2: Package exists - evaluate metadata heuristics

    # 1. Age Factor (Freshness)
    if age_days is not None:
        if age_days <= 7:
            score += 45
            reasons.append(f"Newly born package (Registered {age_days} day(s) ago).")
        elif age_days <= 30:
            score += 30
            reasons.append(f"Very young package (Registered {age_days} days ago).")
        elif age_days <= 90:
            score += 15
            reasons.append(f"Relatively new package (Registered {age_days} days ago).")
        elif age_days >= 365 * 3:
            score -= 30
        elif age_days >= 365:
            score -= 15

    # 2. Popularity / Downloads Factor
    if downloads is not None:
        if downloads < 50:
            score += 25
            reasons.append(f"Near-zero monthly downloads ({downloads} downloads/month).")
        elif downloads < 300:
            score += 15
            reasons.append(f"Extremely low monthly downloads ({downloads} downloads/month).")
        elif downloads >= 1_000_000:
            score -= 35
        elif downloads >= 50_000:
            score -= 20

    # 3. Release History
    if total_releases == 1:
        score += 15
        reasons.append("Single release only (v0.0.1 or v1.0.0, no maintenance history).")
    elif total_releases >= 10:
        score -= 10

    # 4. Source Code Repository
    if not has_repo:
        score += 20
        reasons.append("Ghost repository (No valid GitHub/GitLab source code repository linked).")
    else:
        score -= 15

    # 5. Summary / Description
    if not summary or len(summary.strip()) < 15:
        score += 10
        reasons.append("Empty or placeholder package description.")

    # 6. AI Hallucination Naming Pattern
    if HALLUCINATION_SUFFIX_PATTERN.search(name):
        if age_days is not None and age_days <= 60:
            score += 15
            reasons.append("Matches classic AI hallucination naming pattern with high-frequency suffixes.")

    # Clamp score between 0 and 100
    final_score = max(0, min(100, score))

    if final_score >= 80:
        level = "CRITICAL"
        status = "SUSPECTED_SLOPSQUATTING"
        action = "High probability of malicious slopsquatting or unverified AI dependency. Inspect source code immediately!"
    elif final_score >= 50:
        level = "HIGH"
        status = "SUSPICIOUS_PACKAGE"
        action = "New or low-reputation package. Verify if team member intentionally added this."
    elif final_score >= 25:
        level = "MEDIUM"
        status = "UNCOMMON_PACKAGE"
        action = "Uncommon package with low adoption. Proceed with caution."
    else:
        level = "SAFE"
        status = "ESTABLISHED"
        action = "Established, reputable package with solid community history."

    return {
        "name": name,
        "ecosystem": inspected.get("ecosystem"),
        "version": inspected.get("version"),
        "score": final_score,
        "level": level,
        "status": status,
        "age_days": age_days,
        "monthly_downloads": downloads,
        "total_releases": total_releases,
        "has_repo": has_repo,
        "repo_url": inspected.get("repo_url"),
        "reasons": reasons,
        "action": action
    }
